static const char spki_signed_data[] = "some signed data";

/* Not a well-formed ECDSA or DSA signature, which openssl reports as an error
 * rather than as a signature mismatch.
 */
static const char spki_malformed_signature[] = "AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA";

static bool
validate_spki (const char *data, const guint8 *pubkey, gsize pubkey_size, const void *signature,
               gsize signature_size)
{
  g_autoptr (GBytes) data_bytes = g_bytes_new_static (data, strlen (data));
  g_autoptr (GBytes) pubkey_bytes = g_bytes_new_static (pubkey, pubkey_size);
  g_autoptr (GBytes) signature_bytes = g_bytes_new_static (signature, signature_size);
  bool valid = false;
  g_autoptr (GError) error = NULL;

  g_assert (
      otcore_validate_spki_signature (data_bytes, pubkey_bytes, signature_bytes, &valid, &error));
  g_assert_no_error (error);
  return valid;
}

static void
test_spki_ecdsa (void)
{
  g_assert (validate_spki (spki_signed_data, ec_p256_pubkey, sizeof (ec_p256_pubkey),
                           ec_p256_signature, sizeof (ec_p256_signature)));
  g_assert (!validate_spki ("some other data", ec_p256_pubkey, sizeof (ec_p256_pubkey),
                            ec_p256_signature, sizeof (ec_p256_signature)));
  g_assert (!validate_spki (spki_signed_data, ec_p256_pubkey, sizeof (ec_p256_pubkey),
                            spki_malformed_signature, strlen (spki_malformed_signature)));
  g_assert (!validate_spki (spki_signed_data, ec_p256_pubkey, sizeof (ec_p256_pubkey), "", 0));
}

static void
test_spki_dsa (void)
{
  g_assert (!validate_spki (spki_signed_data, dsa_pubkey, sizeof (dsa_pubkey),
                            spki_malformed_signature, strlen (spki_malformed_signature)));
  g_assert (!validate_spki (spki_signed_data, dsa_pubkey, sizeof (dsa_pubkey), "", 0));
}
