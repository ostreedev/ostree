set -euo pipefail

. $(dirname $0)/libtest.sh

# Exports OSTREE_SYSROOT so --sysroot not needed.
setup_os_repository "archive" "grub2 ostree-grub-generator"

extra_admin_tests=2
folders_instead_symlinks_in_boot=1

. $(dirname $0)/admin-test.sh

# ostree-grub-generator appends to its output file, so the copy of the previous
# grub.cfg in loader.tmp must not be reused.
assert_file_has_content_once sysroot/boot/loader/grub.cfg "This file was generated by"
echo "ok grub.cfg generated from scratch"

# Entries of other operating systems are preserved and end up in grub.cfg, but
# only Linux ones: ostree-grub-generator must skip e.g. EFI entries, or
# dangling symlinks.
cat > sysroot/boot/loader/entries/otheros-linux.conf << EOF
title Other OS's Linux
linux /vmlinuz-otheros
initrd /microcode.img
initrd /initramfs-otheros.img
options quiet
options 100%
EOF
cat > "sysroot/boot/loader/entries/other os.conf" << EOF
title Other OS with a space
linux /vmlinuz-otheros2
EOF
cat > sysroot/boot/loader/entries/otheros-efi.conf << EOF
title Other EFI OS
efi /EFI/otheros/bootx64.efi
EOF
ln -s ../nonexistent sysroot/boot/loader/entries/dangling.conf
${CMD_PREFIX} ostree admin deploy --karg-append=grubtest=1 --os=testos testos:testos/buildmain/x86_64-runtime
assert_file_has_content sysroot/boot/loader/entries/otheros-efi.conf "Other EFI OS"
assert_file_has_content sysroot/boot/loader/grub.cfg "grubtest=1"
assert_file_has_content_literal sysroot/boot/loader/grub.cfg "menuentry 'Other OS'\\''s Linux' {"
assert_file_has_content_literal sysroot/boot/loader/grub.cfg "linux /boot/vmlinuz-otheros quiet 100%"
assert_file_has_content_literal sysroot/boot/loader/grub.cfg "initrd /boot/microcode.img /boot/initramfs-otheros.img"
assert_file_has_content_literal sysroot/boot/loader/grub.cfg "menuentry 'Other OS with a space' {"
assert_not_file_has_content sysroot/boot/loader/grub.cfg "Other EFI OS"
# The first entry is the default one, which must stay ostree's
case "$(grep -m1 '^menuentry' sysroot/boot/loader/grub.cfg)" in
    *Other*) fatal "the first entry of grub.cfg is not ostree's" ;;
esac
echo "ok grub.cfg only has Linux entries"
